import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CATALOG_ENTRIES } from '../packages/contracts/src/dashboards/catalog/registry.ts';
import type { DashboardCatalogEntryDto } from '../packages/contracts/src/dashboards/catalog/dto.ts';
import { toCatalogEntryDto } from '../packages/contracts/src/dashboards/catalog/dto.ts';
import { PRIMITIVES } from '../packages/contracts/src/dashboards/primitives/index.ts';
import { primitivePropsSchema } from '../packages/harnesys/src/packs/dashboards/schemas.ts';

const HEADER = 'Generated by scripts/gen-widget-skill-refs.ts, do not edit';
const OUT_DIR = join(
  import.meta.dir,
  '..',
  'apps',
  'server',
  'assets',
  'skills',
  'widget-creator',
  'references',
);
const MAX_DEPTH = 4;

type SchemaNode = Record<string, unknown>;

interface FieldRow {
  path: string;
  type: string;
}

function asRecord(value: unknown): SchemaNode | undefined {
  if (value === null || typeof value !== 'object' || Array.isArray(value)) {
    return undefined;
  }
  return value as SchemaNode;
}

function asArray(value: unknown): unknown[] {
  return Array.isArray(value) ? value : [];
}

function textOf(value: unknown): string | undefined {
  return typeof value === 'string' ? value : undefined;
}

function escapeCell(value: string): string {
  return value.replaceAll('|', '\\|');
}

function deref(node: SchemaNode, root: SchemaNode): SchemaNode {
  const ref = textOf(node.$ref);
  if (ref === undefined) {
    return node;
  }
  const defs = asRecord(root.$defs);
  const target = defs === undefined ? undefined : asRecord(defs[ref.replace('#/$defs/', '')]);
  return target ?? node;
}

function unionOf(node: SchemaNode): SchemaNode[] {
  return [...asArray(node.anyOf), ...asArray(node.oneOf)]
    .map(asRecord)
    .filter((entry): entry is SchemaNode => entry !== undefined);
}

function typeLabel(node: SchemaNode, root: SchemaNode): string {
  const schema = deref(node, root);
  const options = asArray(schema.enum).map((entry) => JSON.stringify(entry));
  if (options.length > 0) {
    return options.join(' | ');
  }
  const union = unionOf(schema).map((entry) => typeLabel(entry, root));
  if (union.length > 0) {
    return [...new Set(union)].join(' | ');
  }
  const type = schema.type;
  if (Array.isArray(type)) {
    return type.map(String).join(' | ');
  }
  if (type === 'array') {
    const items = asRecord(schema.items);
    return items === undefined ? 'array' : `array of ${typeLabel(items, root)}`;
  }
  if (type === 'object') {
    return 'object';
  }
  return textOf(type) ?? 'any';
}

function walkFields(
  node: SchemaNode,
  root: SchemaNode,
  path: string,
  depth: number,
  rows: Map<string, FieldRow>,
): void {
  if (depth > MAX_DEPTH) {
    return;
  }
  const schema = deref(node, root);
  const union = unionOf(schema);
  if (union.length > 0) {
    for (const entry of union) {
      walkFields(entry, root, path, depth, rows);
    }
    return;
  }
  if (schema.type === 'array') {
    const items = asRecord(schema.items);
    if (items !== undefined) {
      walkFields(items, root, `${path}[]`, depth + 1, rows);
    }
    return;
  }
  const properties = asRecord(schema.properties);
  if (properties === undefined) {
    return;
  }
  for (const [key, value] of Object.entries(properties)) {
    const childPath = path === '' ? key : `${path}.${key}`;
    const child = deref(asRecord(value) ?? {}, root);
    if (!rows.has(childPath)) {
      rows.set(childPath, { path: childPath, type: typeLabel(child, root) });
    }
    walkFields(child, root, childPath, depth + 1, rows);
  }
}

function queryLines(querySchema: SchemaNode | null): string[] {
  if (querySchema === null) {
    return ['Query: none'];
  }
  const properties = asRecord(querySchema.properties);
  if (properties === undefined) {
    return ['Query: none'];
  }
  const required = new Set(asArray(querySchema.required).map(String));
  const lines = ['Query:'];
  for (const [key, value] of Object.entries(properties)) {
    const node = asRecord(value) ?? {};
    const suffix = required.has(key) ? 'required' : 'optional';
    lines.push(`- \`${key}\` — ${typeLabel(node, querySchema)} (${suffix})`);
  }
  return lines;
}

function eventFields(schema: unknown): string {
  const shape = asRecord((schema as { shape?: unknown } | undefined)?.shape);
  if (shape === undefined) {
    return '(none)';
  }
  const keys = Object.keys(shape).sort();
  return keys.length === 0 ? '(none)' : keys.map((key) => `\`${key}\``).join(', ');
}

function renderPrimitives(): string {
  const lines: string[] = [HEADER, '', '# Widget primitives', ''];
  lines.push(
    'Source: `PRIMITIVES` in `packages/contracts/src/dashboards/primitives/`. An item `primitive` must be one of these ids; `props` are validated against the same schema by the server guard.',
    '',
  );
  const descriptors = [...PRIMITIVES].sort((a, b) => a.id.localeCompare(b.id));
  for (const descriptor of descriptors) {
    const props = primitivePropsSchema(descriptor.id);
    lines.push(`## ${descriptor.id} — ${descriptor.title}`, '');
    lines.push(`${descriptor.description}`);
    lines.push('');
    const visibility = descriptor.hidden === true ? ' (legacy, not in the palette)' : '';
    lines.push(`Category: ${descriptor.category}${visibility}`);
    lines.push(
      `Default rect: ${descriptor.layout.defaultW * 32}×${descriptor.layout.defaultH * 32} px; minimum ${descriptor.layout.minW * 32}×${descriptor.layout.minH * 32} px`,
      '',
    );
    const properties = asRecord(props?.properties);
    if (properties === undefined || Object.keys(properties).length === 0) {
      lines.push('Props: none', '');
    } else {
      const required = new Set(asArray(props?.required).map(String));
      lines.push('| Prop | Type | Required | Default | Hint |', '|---|---|---|---|---|');
      for (const [key, value] of Object.entries(properties)) {
        const node = asRecord(value) ?? {};
        const hint = textOf(node.hint) ?? textOf(node.label) ?? '-';
        const isRequired = required.has(key) && node.default === undefined;
        const fallback =
          node.default === undefined ? '-' : `\`${JSON.stringify(node.default)}\``;
        lines.push(
          `| \`${key}\` | ${escapeCell(typeLabel(node, props ?? {}))} | ${isRequired ? 'yes' : 'no'} | ${escapeCell(fallback)} | ${escapeCell(hint)} |`,
        );
      }
      lines.push('');
    }
    const events = Object.entries(descriptor.events).sort(([a], [b]) => a.localeCompare(b));
    if (events.length === 0) {
      lines.push('Events: none', '');
    } else {
      lines.push('| Event | Payload fields |', '|---|---|');
      for (const [name, schema] of events) {
        lines.push(`| \`${name}\` | ${eventFields(schema)} |`);
      }
      lines.push('');
    }
    const defaults = Object.entries(descriptor.defaults);
    lines.push(
      defaults.length === 0
        ? 'Defaults: none'
        : `Defaults: ${defaults.map(([key, value]) => `\`${key}\` = \`${JSON.stringify(value)}\``).join(', ')}`,
      '',
    );
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

function renderCatalog(): string {
  const lines: string[] = [HEADER, '', '# Org API catalog', ''];
  lines.push(
    'Source: `CATALOG_ENTRIES` in `packages/contracts/src/dashboards/catalog/`. `:orgId` is your org id: an orgApi source path is `/orgs/<orgId>/threads`, and any other `/orgs/<orgId>/...` path is still callable, just without typed response fields.',
    '',
  );
  const entries: DashboardCatalogEntryDto[] = CATALOG_ENTRIES.map(toCatalogEntryDto).sort((a, b) =>
    a.id.localeCompare(b.id),
  );
  for (const entry of entries) {
    const responseSchema = entry.responseSchema;
    const rows = new Map<string, FieldRow>();
    walkFields(responseSchema, responseSchema, '', 0, rows);
    lines.push(`## ${entry.id} — ${entry.label}`, '');
    lines.push(`${entry.method} ${entry.path}`);
    lines.push('');
    lines.push(entry.description);
    lines.push('');
    lines.push(
      entry.invalidatedBy.length === 0
        ? 'Invalidated by: nothing'
        : `Invalidated by: ${entry.invalidatedBy.map((topic) => `\`${topic}\``).join(', ')}`,
    );
    lines.push(...queryLines(entry.querySchema));
    lines.push('');
    if (rows.size === 0) {
      lines.push('Response fields: none');
    } else {
      lines.push('| Response path | Type |', '|---|---|');
      for (const row of rows.values()) {
        lines.push(`| \`${escapeCell(row.path)}\` | ${escapeCell(row.type)} |`);
      }
    }
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

function writeReference(name: string, content: string, checkOnly: boolean): boolean {
  if (checkOnly) {
    const current = readFileSync(join(OUT_DIR, name), 'utf8');
    if (current !== content) {
      process.stdout.write(`${name}: out of date\n`);
      return false;
    }
    process.stdout.write(`${name}: up to date\n`);
    return true;
  }
  writeFileSync(join(OUT_DIR, name), content);
  process.stdout.write(`${name}: ${content.split('\n').length - 1} lines\n`);
  return true;
}

const checkOnly = process.argv.includes('--check');
mkdirSync(OUT_DIR, { recursive: true });
const upToDate =
  writeReference('primitives.md', renderPrimitives(), checkOnly) &
  writeReference('org-api-catalog.md', renderCatalog(), checkOnly);
if (checkOnly && !upToDate) {
  process.stdout.write('Run `bun run skills:gen` to regenerate.\n');
  process.exit(1);
}
