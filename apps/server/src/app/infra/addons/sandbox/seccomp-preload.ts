// The generated preload applies the full seccomp deny-list filter (including
// execve) via prctl(PR_SET_SECCOMP) after bun has booted and before the addon
// entry module runs. bwrap sets PR_SET_NO_NEW_PRIVS before exec, so an
// unprivileged prctl is accepted. Without this second stage, denying execve
// in the bwrap --seccomp filter would also block bwrap's own exec of bun.

export function buildSeccompPreload(filter: Uint8Array): string {
  return `// Generated by LauncherLinuxAdapter at spawn time; do not edit.
const FILTER = Uint8Array.from(atob('${Buffer.from(filter).toString('base64')}'), (c) => c.charCodeAt(0));
const PR_SET_SECCOMP = 22;
const SECCOMP_MODE_FILTER = 2;
const LIBC_NAMES = ['libc.so.6', 'libc.musl-x86_64.so.1', 'libc.musl-aarch64.so.1'];
const { dlopen, FFIType, ptr } = await import('bun:ffi');
let libc = null;
for (const name of LIBC_NAMES) {
  try {
    libc = dlopen(name, {
      prctl: {
        args: [FFIType.int, FFIType.u64, FFIType.ptr, FFIType.u64, FFIType.u64],
        returns: FFIType.int,
      },
    });
    break;
  } catch {
    // try the next libc name
  }
}
if (libc === null) {
  throw new Error('addon sandbox: no loadable libc for prctl(PR_SET_SECCOMP)');
}
if (FILTER.length % 8 !== 0) {
  throw new Error('addon sandbox: seccomp filter is not a multiple of 8 bytes');
}
const program = new Uint8Array(16);
const view = new DataView(program.buffer);
view.setUint16(0, FILTER.length / 8, true);
view.setBigUint64(8, BigInt(ptr(FILTER)), true);
const result = libc.symbols.prctl(PR_SET_SECCOMP, SECCOMP_MODE_FILTER, ptr(program), 0, 0);
if (result !== 0) {
  throw new Error('addon sandbox: prctl(PR_SET_SECCOMP) failed with result ' + result);
}
`;
}
